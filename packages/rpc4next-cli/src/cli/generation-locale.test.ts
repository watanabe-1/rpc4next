import fs from "node:fs";
import path from "node:path";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import { cleanupTempDir, makeTempDir, writeTree } from "../test-helpers/tmp-dir.js";
import { clearScanCaches } from "./core/cache.js";
import { scanAppDir } from "./core/route-scanner.js";
import { checkGenerated, generate } from "./generator.js";

describe("locale-independent generation", () => {
  let tmpDir: string;
  const segments = ["ä", "item2", "z", "item10", "[id]"];
  const expectedPathnames = ["/[id]", "/item10", "/item2", "/z", "/%C3%A4"];
  const logger = {
    info: vi.fn<(...args: unknown[]) => void>(),
    success: vi.fn<(...args: unknown[]) => void>(),
    error: vi.fn<(...args: unknown[]) => void>(),
  };

  beforeEach(() => {
    clearScanCaches();
    vi.clearAllMocks();
    tmpDir = makeTempDir();
    const endpoint = {
      "route.ts": "export const GET = () => Response.json({ ok: true });",
      "page.tsx": "export type Query = { q: string }; export default function Page() {}",
    };
    writeTree(tmpDir, { app: Object.fromEntries(segments.map((name) => [name, endpoint])) });
  });

  afterEach(() => {
    vi.restoreAllMocks();
    clearScanCaches();
    cleanupTempDir(tmpDir);
  });

  it("orders scanned routes and pages by UTF-16 code units", () => {
    const result = scanAppDir(path.join(tmpDir, "rpc.ts"), path.join(tmpDir, "app"));

    expect(result.routeManifests?.map(({ pathname }) => pathname)).toEqual(expectedPathnames);
    expect(result.pageManifests?.map(({ pathname }) => pathname)).toEqual(expectedPathnames);
    const positions = ["_id", "item10", "item2", "z", "ä"].map((key) =>
      result.pathStructure.indexOf(`"${key}":`),
    );
    expect(positions.every((position) => position >= 0)).toBe(true);
    expect(positions).toEqual([...positions].sort((a, b) => a - b));
  });

  it("preserves generated bytes and passes check when default collation changes", () => {
    // Simulate host defaults without relying on OS locale configuration.
    expect(new Intl.Collator("en-US").compare("z", "ä")).toBeGreaterThan(0);
    expect(new Intl.Collator("sv-SE").compare("z", "ä")).toBeLessThan(0);
    let defaultLocale = "en-US";
    vi.spyOn(String.prototype, "localeCompare").mockImplementation(function (
      this: string,
      ...[other, locales, options]: Parameters<string["localeCompare"]>
    ) {
      return new Intl.Collator(locales ?? defaultLocale, options).compare(this, other);
    });
    const options = {
      baseDir: path.join(tmpDir, "app"),
      outputPath: path.join(tmpDir, "rpc.ts"),
      paramsFileName: "route-contract.ts",
      logger,
    };
    const generatedFiles = [
      "rpc.ts",
      "rpc-test-manifest.ts",
      ...segments.map((segment) => path.join("app", segment, "route-contract.ts")),
    ];
    const readGenerated = () =>
      generatedFiles.map((file) => fs.readFileSync(path.join(tmpDir, file)));

    generate(options);
    const englishOutput = readGenerated();
    clearScanCaches();
    defaultLocale = "sv-SE";

    const writeSpy = vi.spyOn(fs, "writeFileSync");
    expect(checkGenerated(options)).toBe(true);
    expect(writeSpy).not.toHaveBeenCalled();
    expect(logger.error).not.toHaveBeenCalled();

    generate(options);
    expect(readGenerated()).toEqual(englishOutput);
    expect(writeSpy).not.toHaveBeenCalled();
  });
});
